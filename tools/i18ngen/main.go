// Command i18ngen checks that ar.json and fr.json have exactly the same keys and
// writes internal/i18n/keys_gen.go with one typed constant per message.
// Run from the repository root (task generate) or via go generate in internal/i18n.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"unicode"

	"github.com/omarchaouki/zaytona-go/internal/i18n"
)

func main() {
	dir := "internal/i18n"
	if _, err := os.Stat(filepath.Join(dir, "ar.json")); err != nil {
		dir = "." // go generate runs in the package directory
	}
	ar := load(filepath.Join(dir, "ar.json"))
	fr := load(filepath.Join(dir, "fr.json"))

	missingFr, missingAr := i18n.Diff(ar, fr), i18n.Diff(fr, ar)
	if len(missingFr)+len(missingAr) > 0 {
		fail(fmt.Errorf("ar.json and fr.json differ:\n  missing in fr.json: %v\n  missing in ar.json: %v", missingFr, missingAr))
	}

	keys := make([]string, 0, len(ar))
	for k := range ar {
		keys = append(keys, k)
	}
	sort.Strings(keys)

	var b bytes.Buffer
	b.WriteString("// Code generated by tools/i18ngen. DO NOT EDIT.\n\npackage i18n\n\n// Message keys, one per entry of ar.json / fr.json.\nconst (\n")
	seen := map[string]string{}
	for _, k := range keys {
		name := constName(k)
		if prev, dup := seen[name]; dup {
			fail(fmt.Errorf("keys %q and %q both map to %s", prev, k, name))
		}
		seen[name] = k
		fmt.Fprintf(&b, "\t%s Key = %q\n", name, k)
	}
	b.WriteString(")\n\n// AllKeys lists every generated key.\nvar AllKeys = []Key{\n")
	for _, k := range keys {
		fmt.Fprintf(&b, "\t%s,\n", constName(k))
	}
	b.WriteString("}\n")

	src, err := format.Source(b.Bytes())
	if err != nil {
		fail(err)
	}
	out := filepath.Join(dir, "keys_gen.go")
	if old, err := os.ReadFile(out); err == nil && bytes.Equal(old, src) { // #nosec G304 -- fixed path
		return
	}
	if err := os.WriteFile(out, src, 0o600); err != nil {
		fail(err)
	}
}

// constName: "orderForm.step1.title" -> "OrderFormStep1Title".
func constName(key string) string {
	var sb strings.Builder
	for _, part := range strings.FieldsFunc(key, func(r rune) bool { return r == '.' || r == '_' || r == '-' }) {
		r := []rune(part)
		r[0] = unicode.ToUpper(r[0])
		sb.WriteString(string(r))
	}
	return sb.String()
}

func load(path string) map[string]string {
	raw, err := os.ReadFile(path) // #nosec G304 -- fixed paths in the repo
	if err != nil {
		fail(err)
	}
	m, err := i18n.Flatten(raw)
	if err != nil {
		fail(fmt.Errorf("%s: %w", path, err))
	}
	return m
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "i18ngen:", err)
	os.Exit(1)
}
